    '## O problema do "lapsed listener"',
    '',
    'Imagina uma abelha que se muda pra outra colmeia, mas nunca cancela a assinatura da Gazeta. O Carteiro continua guardando uma referência pra ela na lista de assinantes pra sempre — mesmo que ninguém mais use essa abelha em nenhum outro lugar do código. Isso é um vazamento de memória clássico, especialmente comum em interfaces gráficas: uma tela é fechada, mas continua "viva" na memória porque ainda está inscrita em algum Subject de longa duração.',
