    '5. Cada **assinante concreto** decide o que fazer com a edição recebida — o carteiro não sabe nem se importa se ela vai ler na hora, guardar numa prateleira, ou repassar pra outra abelha.',
    '',
    '## O fluxo, de um jeito simples',
    '',
    '```mermaid',
    'flowchart LR',
    '    A[Carteiro publica edição nova] --> B[distribuirParaTodos]',
    '    B --> C[AbelhaOperaria.receberEdicao]',
    '    B --> D[AbelhaRainha.receberEdicao]',
    '    B --> E[GuardaDaColmeia.receberEdicao]',
    '```',
    '',
