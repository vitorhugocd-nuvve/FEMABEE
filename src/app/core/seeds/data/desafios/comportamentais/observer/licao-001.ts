    '    public void inscrever(Assinante assinante) {',
    '        assinantes.add(assinante);',
    '    }',
    '',
    '    public void publicarNovaEdicao(String edicao) {',
    '        this.edicaoAtual = edicao;',
    '        distribuirParaTodos();',
    '    }',
    '',
    '    private void distribuirParaTodos() {',
