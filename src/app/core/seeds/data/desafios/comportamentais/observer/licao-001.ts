    '',
    'A colmeia publica um jornalzinho periódico, a **Gazeta da Colmeia**. Toda vez que sai uma edição nova, o **Carteiro da Colmeia** precisa entregar pra cada abelha que assina. Se o código do carteiro tiver que chamar cada abelha assinante pelo nome, uma por uma, toda vez que uma abelha nova assinar, alguém vai precisar lembrar de ir lá e adicionar mais uma entrega.',
    '',
    '## Por que isso importa?',
    '',
    'Sem o padrão, o código de quem publica a gazeta ficaria assim:',
