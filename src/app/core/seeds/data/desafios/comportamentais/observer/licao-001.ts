    '    abelhaOperaria.receberEdicao(edicao);',
    '    abelhaRainha.receberEdicao(edicao);',
    '    guardaDaColmeia.receberEdicao(edicao);',
    '    // toda abelha nova que assinar = mais uma linha aqui, e alguém tem que lembrar de adicionar',
    '}',
    '```',
    '',
    'O padrão **Observer** resolve isso definindo uma relação **um-para-muitos**: quando o Carteiro (o *Subject*) publica uma edição nova, **todas** as abelhas inscritas (os *Observers*) são avisadas automaticamente — sem que o carteiro precise conhecer cada uma pelo nome, só que elas implementam uma interface em comum (uma "caixa de correio" padrão que ele sabe entregar).',
    '',
    '## Como funciona, passo a passo',
    '',
    '1. Define-se uma interface **Assinante** com um método, ex.: `receberEdicao(String edicao)`.',
