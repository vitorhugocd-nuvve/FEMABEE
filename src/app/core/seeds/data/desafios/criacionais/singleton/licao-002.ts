    '',
    '## Um problema que o Singleton simples não resolve',
    '',
    'Imagina que cada colmeia regional da rede precisa da sua própria central de rádio — mas só **uma** central por colmeia, nunca duas disputando o mesmo canal. Um Singleton clássico não serve aqui: ele te dá **uma instância pro programa inteiro**, não uma por colmeia.',
    '',
    'A solução é uma variação do Singleton chamada **Multiton**: em vez de guardar uma única instância num campo, a classe guarda um **registro de instâncias**, uma para cada chave.',
    '',
    '## Como funciona, passo a passo',
    '',
    '1. A classe continua escondendo o construtor, exatamente como no Singleton simples — ninguém de fora cria instâncias com `new`.',
    '2. Em vez de um campo `instancia`, ela guarda um **mapa** (`Map<Chave, Instancia>`) — um registro de "qual instância pertence a qual chave".',
